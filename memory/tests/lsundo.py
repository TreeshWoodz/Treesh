import asyncio, sys, json
from playwright.async_api import async_playwright
EXE="/pw-browsers/chromium_headless_shell-1208/chrome-linux/headless_shell"
LIVE={'songs':'/tmp/live_songs.dot.html','lyrics':'/tmp/live_lyrics.dot.html','icons':'/tmp/live_icons.dot.html'}
MOB=len(sys.argv)>1 and sys.argv[1]=='m'
ok=0; bad=0
def chk(n,c,x=''):
    global ok,bad
    if c: ok+=1; print('PASS',n)
    else: bad+=1; print('FAIL',n,x)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=EXE, args=['--autoplay-policy=no-user-gesture-required'])
        ctx = await b.new_context(**(p.devices['iPhone 13'] if MOB else {'viewport':{'width':1400,'height':850}}))
        pg = await ctx.new_page(); pg.on('pageerror', lambda e: print('PAGEERR', e))
        async def live(route):
            k=[x for x in LIVE if ('/content/'+x) in route.request.url][0]
            await route.fulfill(status=200, content_type='text/html', body=open(LIVE[k],encoding='utf-8').read())
        await pg.route('**/content/songs*', live); await pg.route('**/content/lyrics*', live); await pg.route('**/content/icons*', live)
        await pg.goto('http://localhost:3000/'); await pg.evaluate("()=>{localStorage.setItem('treesh_whatsnew_off','true'); localStorage.setItem('treesh_eco_seen','1'); localStorage.setItem('treesh_profile', JSON.stringify({nickname:'Tester',birthday:'2000-01-01'}));}"); await pg.reload(); await pg.wait_for_timeout(3500)
        sid = await pg.evaluate("()=>{ const s=SONGS.find(x=>x.title==='Cherry'); openLyricSync(s.id); return s.id; }"); await pg.wait_for_timeout(1500)
        await pg.evaluate("()=>{ if(state.ls.mode!=='write') lsSetMode('write'); }"); await pg.wait_for_timeout(400)
        U=pg.locator('[data-testid=ls-undo]'); R=pg.locator('[data-testid=ls-redo]')
        chk('buttons exist', await U.count()==1 and await R.count()==1)
        chk('both disabled at start', await U.is_disabled() and await R.is_disabled())
        v0 = await pg.evaluate("()=>document.getElementById('ls-write').value")
        # header fits
        hd = await pg.evaluate("()=>{ const h=document.querySelector('.lsx-head'); const t=h.querySelector('.min-w-0.flex-1'); return {sw:h.scrollWidth,cw:h.clientWidth,tw:t.getBoundingClientRect().width}; }")
        chk('header fits', hd['sw']<=hd['cw']+1 and hd['tw']>=70, hd)
        await pg.screenshot(path=f'/tmp/lfh_head_{"m" if MOB else "d"}.png')
        # real typing at the end of line 2
        await pg.evaluate("""()=>{ const ta=document.getElementById('ls-write'); ta.focus(); const row=ta.children[1]; const r=document.createRange(); r.selectNodeContents(row); r.collapse(false); const s=getSelection(); s.removeAllRanges(); s.addRange(r); }""")
        await pg.keyboard.type(' hello world', delay=40); await pg.wait_for_timeout(900)
        v1 = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('typed', 'hello world' in v1, v1[:120])
        chk('undo enabled after typing', not await U.is_disabled())
        await U.click(); await pg.wait_for_timeout(300)
        va = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('undo removes last word', 'hello' in va and 'world' not in va, va.split('\n')[1])
        chk('redo enabled', not await R.is_disabled())
        await U.click(); await pg.wait_for_timeout(300)
        vb = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('undo back to original', vb==v0, vb.split('\n')[1])
        chk('undo disabled at the start', await U.is_disabled())
        chk('dirty dot hidden at original', await pg.evaluate("()=>document.getElementById('ls-dirty').classList.contains('hidden')&&!state.ls.dirty"))
        await R.click(); await pg.wait_for_timeout(200); await R.click(); await pg.wait_for_timeout(300)
        vc = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('redo twice = typed text', vc==v1, vc.split('\n')[1])
        chk('focus kept in editor', await pg.evaluate("()=>document.activeElement&&document.activeElement.id==='ls-write'"))
        # keyboard shortcuts
        await pg.keyboard.type(' yo', delay=40); await pg.wait_for_timeout(100)
        await pg.keyboard.press('Control+z'); await pg.wait_for_timeout(300)
        vd = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('Ctrl+Z undoes pending typing', 'yo' not in vd.split('\n')[1] and vd.split('\n')[1].rstrip()==vc.split('\n')[1].rstrip(), vd.split('\n')[1])
        await pg.keyboard.press('Control+Shift+z'); await pg.wait_for_timeout(300)
        ve = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('Ctrl+Shift+Z redoes', ' yo' in ve.split('\n')[1], ve.split('\n')[1])
        await pg.keyboard.press('Control+z'); await pg.wait_for_timeout(200); await pg.keyboard.press('Control+y'); await pg.wait_for_timeout(300)
        vf = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('Ctrl+Y redoes', vf==ve)
        # bold is its own step
        await pg.evaluate("""()=>{ const ta=document.getElementById('ls-write'); const row=ta.children[1]; const r=document.createRange(); r.selectNodeContents(row); const s=getSelection(); s.removeAllRanges(); s.addRange(r); }""")
        await pg.keyboard.press('Control+b'); await pg.wait_for_timeout(200)
        vg = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('bold applied', '**' in vg.split('\n')[1], vg.split('\n')[1])
        await pg.keyboard.press('Control+z'); await pg.wait_for_timeout(300)
        vh = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('undo bold only', vh==vf, vh.split('\n')[1])
        # save point
        await pg.evaluate("()=>lsSave()"); await pg.wait_for_timeout(300)
        chk('saved -> clean', await pg.evaluate("()=>!state.ls.dirty"))
        await U.click(); await pg.wait_for_timeout(300)
        chk('undo after save -> dirty', await pg.evaluate("()=>state.ls.dirty&&!document.getElementById('ls-dirty').classList.contains('hidden')"))
        await R.click(); await pg.wait_for_timeout(300)
        chk('redo to saved -> clean', await pg.evaluate("()=>!state.ls.dirty"))
        # sync mode: stamps + cross-mode undo
        has = await pg.evaluate("()=>state.ls.hasAudio")
        if has:
            await pg.evaluate("()=>lsSetMode('sync')"); await pg.wait_for_timeout(500)
            t0 = await pg.evaluate("()=>{ const i=state.ls.items.findIndex(x=>x.type==='line'); return [i,state.ls.items[i].t]; }")
            await pg.evaluate("(i)=>{ lsNudge(i,0.5); }", t0[0]); await pg.wait_for_timeout(100)
            await pg.evaluate("(i)=>{ lsNudge(i,0.5); }", t0[0]); await pg.wait_for_timeout(100)
            t1 = await pg.evaluate("(i)=>state.ls.items[i].t", t0[0])
            chk('nudged', abs((t1 or 0)-((t0[1] or 0)+1))<0.02, [t0,t1])
            await U.click(); await pg.wait_for_timeout(300)
            t2 = await pg.evaluate("(i)=>state.ls.items[i].t", t0[0])
            chk('undo one nudge', abs((t2 or 0)-((t0[1] or 0)+0.5))<0.02, t2)
            chk('sync rows rendered', await pg.locator('#ls-lines .ls-line').count()>3)
            await U.click(); await pg.wait_for_timeout(200)
            t3 = await pg.evaluate("(i)=>state.ls.items[i].t", t0[0])
            chk('undo second nudge', t3==t0[1], [t3,t0])
            # keep undoing into the Write edits from Sync
            await U.click(); await pg.wait_for_timeout(300)
            txt = await pg.evaluate("()=>state.ls.items.filter(x=>x.type==='line')[0].text")
            chk('undo in Sync reaches Write edits', ' yo' not in txt, txt)
            await pg.screenshot(path=f'/tmp/lfh_sync_{"m" if MOB else "d"}.png')
            await R.click(); await pg.wait_for_timeout(300)
            await pg.evaluate("()=>lsSetMode('write')"); await pg.wait_for_timeout(400)
            vi = await pg.evaluate("()=>document.getElementById('ls-write').value")
            chk('back in write shows redone text', ' yo' in vi.split('\n')[1], vi.split('\n')[1])
        # verses panel: own steps, undo + redo
        await pg.evaluate("()=>lsvOpen()"); await pg.wait_for_timeout(700)
        n0 = await pg.locator('#lsv .lsv-card').count()
        chk('panel undo/redo disabled', await pg.locator('[data-testid=lsv-undo]').is_disabled() and await pg.locator('[data-testid=lsv-redo]').is_disabled())
        await pg.locator('[data-testid=lsv-add-section]').click(); await pg.wait_for_timeout(400)
        chk('section added', await pg.locator('#lsv .lsv-card').count()==n0+1)
        await pg.locator('[data-testid=lsv-undo]').click(); await pg.wait_for_timeout(400)
        chk('panel undo', await pg.locator('#lsv .lsv-card').count()==n0)
        await pg.locator('[data-testid=lsv-redo]').click(); await pg.wait_for_timeout(400)
        chk('panel redo', await pg.locator('#lsv .lsv-card').count()==n0+1)
        await pg.locator('#lsv [data-lsv-lines]').last.click(); await pg.keyboard.type('fresh line', delay=30); await pg.wait_for_timeout(300)
        chk('panel undo enabled while typing', not await pg.locator('[data-testid=lsv-undo]').is_disabled())
        await pg.keyboard.press('Control+z'); await pg.wait_for_timeout(400)
        lastv = await pg.evaluate("()=>{ const e=[...document.querySelectorAll('#lsv [data-lsv-lines]')].pop(); return e.value; }")
        chk('Ctrl+Z in panel card undoes typing', 'fresh' not in lastv, lastv)
        await pg.keyboard.press('Control+Shift+z'); await pg.wait_for_timeout(400)
        lastv = await pg.evaluate("()=>{ const e=[...document.querySelectorAll('#lsv [data-lsv-lines]')].pop(); return e.value; }")
        chk('Ctrl+Shift+Z in panel redoes', 'fresh line' in lastv, lastv)
        await pg.screenshot(path=f'/tmp/lfh_lsv_{"m" if MOB else "d"}.png')
        await pg.locator('[data-testid=lsv-save]').click(); await pg.wait_for_timeout(700)
        vj = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('panel saved into lyrics', 'fresh line' in vj)
        await U.click(); await pg.wait_for_timeout(300)
        vk = await pg.evaluate("()=>document.getElementById('ls-write').value")
        chk('one undo removes the whole Verses change', 'fresh line' not in vk and '[Verse' in vk, vk[-80:])
        # close clears history
        await pg.evaluate("()=>closeLS(true)"); await pg.wait_for_timeout(300)
        await pg.evaluate("(id)=>openLyricSync(id)", sid); await pg.wait_for_timeout(900)
        chk('reopen: history cleared', await pg.locator('[data-testid=ls-undo]').is_disabled() and await pg.locator('[data-testid=ls-redo]').is_disabled())
        # light paper look
        await pg.evaluate("()=>{ state.theme='light'; renderLS(); }"); await pg.wait_for_timeout(500)
        await pg.screenshot(path=f'/tmp/lfh_light_{"m" if MOB else "d"}.png')
        print('RESULT', ok, 'pass', bad, 'fail')
        await b.close()
asyncio.run(main())
